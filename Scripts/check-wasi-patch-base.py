def as_carried(*texts):
    return {'Scripts/patches/%04d-fixture.patch' % (index + 10): parse_patch(text)
            for index, text in enumerate(texts)}


def as_carried_named(name, text):
    return {'Scripts/patches/' + name: parse_patch(text)}


def as_wasi(*texts):
    return {'Scripts/patches-wasi/wasi-fixture-%d.patch' % index:
            {'text': text, 'hunks': parse_patch(text)}
            for index, text in enumerate(texts)}


def self_test():
    carried_static = as_carried_named(
        '0033-Interface_Static-thread-safety-mutex-1157.patch', CARRIED_MUTEX)

    cases = [
        ('#2076: a WASI patch quoting a line the carried set deletes',
         'rule 3. The carried mutex patch removes `return aTable;` and this diff quotes it as '
         'context, which is proof the diff was cut from the unpatched source',
         carried_static, as_wasi(WASI_STALE), ['CARRIED_COLLISION', 'STALE_CONTEXT']),

        ('a WASI patch sharing a file with a carried patch and declaring nothing',
         'rule 1 on its own: the hunks do not overlap and no context is stale, so rule 3 is '
         'silent and only the undeclared collision fires',
         carried_static, as_wasi(WASI_COLLIDING), ['CARRIED_COLLISION']),

        ('the same patch with `Applies-After:` naming the carried patch (correct)',
         'rule 1\'s escape hatch, which is the whole reason the rule is usable: a legitimate '
         'overlap is declared once and stays green until the carried patch moves',
         carried_static, as_wasi(WASI_COLLIDING_DECLARED), []),

        ('`Applies-After:` naming a patch that is not in Scripts/patches/',
         'rule 2, the repin tripwire: a retired or renumbered carried patch leaves the trailer '
         'pointing at a state that no longer exists, and the declaration must stop working',
         carried_static, as_wasi(WASI_TRAILER_UNKNOWN), ['STALE_TRAILER']),

        ('#2076: OSD_File\'s `myFileChannel` pasted into OSD_Directory',
         'rule 4, and it is the only rule that fires on #2076\'s wasi-osd-directory.patch, whose '
         'base was correct: it applies to both trees and its index blobs match',
         as_carried(), as_wasi(WASI_FOREIGN_MEMBER), ['FOREIGN_MEMBER']),

        ('an added line writing a member the hunk shows in context (correct)',
         'rule 4\'s known-member vocabulary. Without it every WASI patch that touches a member at '
         'all would be reported',
         as_carried(), as_wasi(WASI_KNOWN_MEMBER), []),

        ('a member declared in the header patch and used in the implementation patch (correct)',
         'rule 4\'s DECL_RE and the .cxx/.hxx pooling in class_stem, which is #2076\'s mySpinlock '
         'exactly: declared in wasi-incallocator.hxx.patch, used in wasi-incallocator.cxx.patch',
         as_carried(), as_wasi(WASI_DECLARES_MEMBER, WASI_USES_DECLARED_MEMBER), []),

        ('a carried patch removing a lone brace that a WASI patch quotes (correct)',
         'rule 3\'s substantive() filter. A brace, a blank or a short line appears in every OCCT '
         'file, so matching one is coincidence rather than evidence',
         as_carried_named('0016-fixture.patch', CARRIED_TRIVIAL),
         as_wasi(WASI_TRIVIAL_CONTEXT), ['CARRIED_COLLISION']),

        ('two WASI patches editing the same file',
         'rule 5. Each is individually fine; what is wrong is that the second states its line '
         'numbers against whatever the first left, and filename order is not a decision',
         as_carried(), as_wasi(WASI_KNOWN_MEMBER, WASI_SECOND_ON_SAME_FILE),
         ['COINCIDENT_TARGET']),

        ('a prose preamble whose bullet names the very member rule 4 looks for',
         'the count-driven hunk parser. A parser that read `- myFileChannel is deliberately ...` '
         'as a removed line would add the member to the known vocabulary and report the patch '
         'clean, which is the blind-detector failure this family exists to prevent',
         as_carried(), as_wasi(PROSE_PREAMBLE), ['FOREIGN_MEMBER']),
    ]

    failed = 0
    print('patch-text cases')
    for name, isolates, carried, wasi, expected in cases:
        found, _ = findings(carried, wasi)
        got = sorted(kind for kind, _, _, _ in found)
        ok = got == sorted(expected)
        failed += not ok
        print('  %s %s' % ('ok  ' if ok else 'MISS', name))
        print('       isolates: %s' % isolates)
        if not ok:
            print('       expected %s, got %s' % (sorted(expected), got))

    print('parser cases')
    parser_cases = [
        ('a normal patch parses to at least one hunk', len(parse_patch(WASI_STALE)) >= 1),
        # Not decorative: every fixture here was first written with a hand-guessed `@@` count, and
        # an over-large count makes the parser consume the NEXT hunk header as body, so a two-hunk
        # fixture parses to one and the rule it exercises reports nothing while the fixture looks
        # correct. This is the assertion that separates the two.
        ('every fixture parses to as many hunks as it has `@@` headers',
         all(len(parse_patch(text)) == text.count('\n@@ ') + text.startswith('@@ ')
             for text in (CARRIED_MUTEX, WASI_STALE, WASI_COLLIDING, WASI_FOREIGN_MEMBER,
                          WASI_KNOWN_MEMBER, WASI_DECLARES_MEMBER, WASI_USES_DECLARED_MEMBER,
                          CARRIED_TRIVIAL, WASI_TRIVIAL_CONTEXT, WASI_SECOND_ON_SAME_FILE,
                          PROSE_PREAMBLE, INDEXED))),
        ('a patch with no hunk header parses to none',
         len(parse_patch('just prose, no diff at all\n')) == 0),
        ('a trailer outside a hunk body is read',
         parse_trailers(WASI_COLLIDING_DECLARED)
         == ['0033-Interface_Static-thread-safety-mutex-1157.patch']),
        ('a patch with no trailer yields none', parse_trailers(WASI_COLLIDING) == []),
        ('an `index` line is read against the right target',
         parse_index(INDEXED) == {'src/FoundationClasses/TKernel/OSD/OSD_Path.cxx':
                                  ('a39c0c84', '792070c6')}),
        ('a hand-trimmed patch has no index stamp, which is not a defect',
         parse_index(WASI_STALE) == {}),
        ('class_stem pools .cxx with .hxx',
         class_stem('a/OSD_File.cxx') == class_stem('b/OSD_File.hxx') == 'OSD_File'),
        ('substantive() rejects a lone brace and accepts a statement',
         not substantive('  {  ') and substantive('  return aTable;  ')),
        ('DECL_RE separates a declaration from an assignment',
         DECL_RE.match('  std::atomic_flag mySpinlock;') is not None
         and DECL_RE.match('  myFileChannel = open(aTmpName, O_CREAT, 0600);') is None),
    ]
    for name, ok in parser_cases:
        failed += not ok
        print('  %s %s' % ('ok  ' if ok else 'MISS', name))

    total = len(cases) + len(parser_cases)
    print('%d/%d cases correct' % (total - failed, total))
    return 1 if failed else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--self-test', action='store_true',
                        help='run the fixture battery instead of the repo')
    parser.add_argument('--list', action='store_true',
                        help='print each WASI patch\'s targets, trailers and index stamps')
    parser.add_argument('--tree', nargs='?', const=DEFAULT_TREE, default=None, metavar='DIR',
                        help='also run the real `git apply --check` in this checkout with the '
                             'carried set applied (default %s); not part of gate-scripts, which '
                             'has no checkout' % DEFAULT_TREE)
    parser.add_argument('--require-tree', action='store_true',
                        help='fail rather than skip when --tree examined nothing (#2098)')
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    if args.list:
        return list_inventory()
    if args.require_tree and args.tree is None:
        args.tree = DEFAULT_TREE
    return run(tree=args.tree, require_tree=args.require_tree)


